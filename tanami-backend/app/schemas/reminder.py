"""Reminder, weather and home-screen schemas."""

from __future__ import annotations

from datetime import datetime

from app.domain import ReminderPriority, ReminderStatus, ReminderType
from app.schemas.base import ApiModel


class ReminderOut(ApiModel):
    id: str
    type: ReminderType
    priority: ReminderPriority
    status: ReminderStatus
    title: str
    body: str
    payload: dict[str, object]
    plant_id: str | None
    farm_id: str | None
    valid_until: datetime | None
    sent_at: datetime | None
    read_at: datetime | None
    created_at: datetime


class ReminderUpdate(ApiModel):
    """Only the status is mutable: the content is generated by the rule engine."""

    status: ReminderStatus


class WeatherSlotOut(ApiModel):
    local_datetime: str
    t: float | None
    hu: float | None
    weather_desc: str
    ws: float | None
    wd: str
    tp: float | None = None


class WeatherDayOut(ApiModel):
    date: str
    slots: list[WeatherSlotOut]


class WeatherOut(ApiModel):
    adm4_code: str
    source: str
    fetched_at: datetime
    attribution: str
    is_stale: bool = False
    days: list[WeatherDayOut]


class PlantAttention(ApiModel):
    id: str
    label: str
    farm_id: str
    health_status: str
    reason: str


class HomeOut(ApiModel):
    weather: WeatherOut | None
    reminders: list[ReminderOut]
    plants_needing_attention: list[PlantAttention]
    unread_reminder_count: int
